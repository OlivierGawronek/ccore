use std::collections::{HashMap, HashSet};
use std::fmt::Write;

use crate::ast::*;
use crate::checker::BUILTIN_PRINTLN;

/// Translates a checked program into a single C11 translation unit.
pub fn generate(program: &Program, src: &str, source_name: &str) -> String {
    let mut cg = Codegen {
        out: String::new(),
        indent: 0,
        line_starts: std::iter::once(0)
            .chain(src.match_indices('\n').map(|(i, _)| i + 1))
            .collect(),
        scopes: Vec::new(),
        used_names: HashSet::new(),
    };
    cg.emit_prelude(source_name);
    cg.emit_program(program);
    cg.out
}

struct Codegen {
    out: String,
    indent: usize,
    line_starts: Vec<usize>,
    scopes: Vec<HashMap<String, String>>,
    /// C names already taken in the current function.
    used_names: HashSet<String>,
}

fn c_type(ty: Type) -> &'static str {
    match ty {
        Type::I32 => "int32_t",
        Type::I64 => "int64_t",
        Type::Bool => "bool",
        Type::Void => "void",
        Type::Str => unreachable!("str values never reach codegen outside println"),
    }
}

fn c_string(s: &str) -> String {
    let mut out = String::from("\"");
    for &b in s.as_bytes() {
        match b {
            b'"' => out.push_str("\\\""),
            b'\\' => out.push_str("\\\\"),
            b'\n' => out.push_str("\\n"),
            b'\t' => out.push_str("\\t"),
            b'\r' => out.push_str("\\r"),
            // `??=` and friends are trigraphs in strict C11 mode.
            b'?' => out.push_str("\\?"),
            0x20..=0x7e => out.push(b as char),
            _ => write!(out, "\\{b:03o}").unwrap(),
        }
    }
    out.push('"');
    out
}

fn c_int_literal(value: i64, ty: Type) -> String {
    match ty {
        Type::I32 if value == i32::MIN as i64 => "INT32_MIN".to_string(),
        Type::I64 => format!("INT64_C({value})"),
        _ => value.to_string(),
    }
}

fn fn_name(name: &str) -> String {
    format!("f_{name}")
}

const INCLUDES: &str = "#include <inttypes.h>
#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
";

const PANIC: &str = r#"
static void ccore_panic(const char *msg, int line) {
    fflush(stdout);
    fprintf(stderr, "panic at %s:%d: %s\n", ccore_source, line, msg);
    exit(101);
}
"#;

impl Codegen {
    fn line(&mut self, text: &str) {
        for _ in 0..self.indent {
            self.out.push_str("    ");
        }
        self.out.push_str(text);
        self.out.push('\n');
    }

    fn source_line(&self, offset: usize) -> usize {
        self.line_starts.partition_point(|&start| start <= offset)
    }

    fn emit_prelude(&mut self, source_name: &str) {
        writeln!(
            self.out,
            "// Generated by ccore from {source_name}. Do not edit.\n"
        )
        .unwrap();
        self.out.push_str(INCLUDES);
        writeln!(
            self.out,
            "\nstatic const char *ccore_source = {};",
            c_string(source_name)
        )
        .unwrap();
        self.out.push_str(PANIC);

        // Signed overflow is UB in C, so every arithmetic op goes through a checked helper.
        for (suffix, t, min) in [
            ("i32", "int32_t", "INT32_MIN"),
            ("i64", "int64_t", "INT64_MIN"),
        ] {
            for (op, builtin) in [("add", "add"), ("sub", "sub"), ("mul", "mul")] {
                write!(
                    self.out,
                    "
static inline {t} ccore_{op}_{suffix}({t} a, {t} b, int line) {{
    {t} r;
    if (__builtin_{builtin}_overflow(a, b, &r)) ccore_panic(\"integer overflow\", line);
    return r;
}}
"
                )
                .unwrap();
            }
            write!(
                self.out,
                "
static inline {t} ccore_div_{suffix}({t} a, {t} b, int line) {{
    if (b == 0) ccore_panic(\"division by zero\", line);
    if (a == {min} && b == -1) ccore_panic(\"integer overflow\", line);
    return a / b;
}}

static inline {t} ccore_rem_{suffix}({t} a, {t} b, int line) {{
    if (b == 0) ccore_panic(\"remainder by zero\", line);
    if (a == {min} && b == -1) ccore_panic(\"integer overflow\", line);
    return a % b;
}}

static inline {t} ccore_neg_{suffix}({t} a, int line) {{
    if (a == {min}) ccore_panic(\"integer overflow\", line);
    return -a;
}}
"
            )
            .unwrap();
        }
        self.out.push('\n');
    }

    fn signature(&self, func: &Function) -> String {
        let ret = func
            .ret
            .as_ref()
            .map_or(Type::Void, |t| crate::checker::resolve_type(t).unwrap());
        let params: Vec<String> = func
            .params
            .iter()
            .map(|p| {
                let ty = crate::checker::resolve_type(&p.ty).unwrap();
                format!("{} v_{}", c_type(ty), p.name)
            })
            .collect();
        let params = if params.is_empty() {
            "void".to_string()
        } else {
            params.join(", ")
        };
        format!("static {} {}({params})", c_type(ret), fn_name(&func.name))
    }

    fn emit_program(&mut self, program: &Program) {
        for func in &program.functions {
            let sig = self.signature(func);
            self.line(&format!("{sig};"));
        }

        for func in &program.functions {
            self.out.push('\n');
            self.emit_function(func);
        }

        let main_returns_value = program
            .functions
            .iter()
            .find(|f| f.name == "main")
            .is_some_and(|f| f.ret.is_some());
        self.out.push_str("\nint main(void) {\n");
        if main_returns_value {
            self.out.push_str("    return f_main();\n");
        } else {
            self.out.push_str("    f_main();\n    return 0;\n");
        }
        self.out.push_str("}\n");
    }

    fn emit_function(&mut self, func: &Function) {
        self.used_names.clear();
        self.scopes.push(HashMap::new());
        for p in &func.params {
            self.declare_local(&p.name);
        }

        let sig = self.signature(func);
        self.line(&format!("{sig} {{"));
        self.emit_block_body(&func.body);
        self.line("}");
        self.scopes.pop();
    }

    /// Every `let` gets its own C name. Besides shadowing in the same scope, this
    /// avoids C's rule that `int x = x;` refers to the new, uninitialized `x`.
    fn declare_local(&mut self, name: &str) -> String {
        let mut c_name = format!("v_{name}");
        let mut n = 1;
        while self.used_names.contains(&c_name) {
            c_name = format!("v_{name}_{n}");
            n += 1;
        }
        self.used_names.insert(c_name.clone());
        self.scopes
            .last_mut()
            .unwrap()
            .insert(name.to_string(), c_name.clone());
        c_name
    }

    fn lookup(&self, name: &str) -> &str {
        self.scopes
            .iter()
            .rev()
            .find_map(|scope| scope.get(name))
            .expect("checker guarantees variables exist")
    }

    fn emit_block_body(&mut self, block: &Block) {
        self.indent += 1;
        self.scopes.push(HashMap::new());
        for stmt in &block.stmts {
            self.emit_stmt(stmt);
        }
        self.scopes.pop();
        self.indent -= 1;
    }

    fn emit_stmt(&mut self, stmt: &Stmt) {
        match &stmt.kind {
            StmtKind::Let { name, value, .. } => {
                let init = self.expr(value);
                let ty = c_type(value.ty.unwrap());
                let c_name = self.declare_local(name);
                self.line(&format!("{ty} {c_name} = {init};"));
            }
            StmtKind::Assign { name, value, .. } => {
                let value = self.expr(value);
                let target = self.lookup(name).to_string();
                self.line(&format!("{target} = {value};"));
            }
            StmtKind::If { .. } => self.emit_if(stmt, "if"),
            StmtKind::While { cond, body } => {
                let cond = self.condition(cond);
                self.line(&format!("while ({cond}) {{"));
                self.emit_block_body(body);
                self.line("}");
            }
            StmtKind::Return(None) => self.line("return;"),
            StmtKind::Return(Some(value)) => {
                let value = self.expr(value);
                self.line(&format!("return {value};"));
            }
            StmtKind::Block(block) => {
                self.line("{");
                self.emit_block_body(block);
                self.line("}");
            }
            StmtKind::Expr(expr) => {
                let code = self.expr(expr);
                if matches!(expr.kind, ExprKind::Call { .. }) {
                    self.line(&format!("{code};"));
                } else {
                    self.line(&format!("(void)({code});"));
                }
            }
        }
    }

    fn emit_if(&mut self, stmt: &Stmt, keyword: &str) {
        let StmtKind::If {
            cond,
            then_block,
            else_block,
        } = &stmt.kind
        else {
            unreachable!()
        };

        let cond = self.condition(cond);
        self.line(&format!("{keyword} ({cond}) {{"));
        self.emit_block_body(then_block);

        match else_block {
            Some(block)
                if block.stmts.len() == 1 && matches!(block.stmts[0].kind, StmtKind::If { .. }) =>
            {
                self.emit_if(&block.stmts[0], "} else if");
            }
            Some(block) => {
                self.line("} else {");
                self.emit_block_body(block);
                self.line("}");
            }
            None => self.line("}"),
        }
    }

    /// Like `expr`, but drops the outer parentheses that `if (...)` already provides.
    fn condition(&mut self, expr: &Expr) -> String {
        let code = self.expr(expr);
        match &expr.kind {
            ExprKind::Binary { op, .. } if !op.is_arithmetic() => {
                code[1..code.len() - 1].to_string()
            }
            _ => code,
        }
    }

    fn expr(&mut self, expr: &Expr) -> String {
        let ty = expr.ty.expect("checker assigns a type to every expression");
        match &expr.kind {
            ExprKind::Int(value) => c_int_literal(*value, ty),
            ExprKind::Bool(b) => b.to_string(),
            ExprKind::Str(s) => c_string(s),
            ExprKind::Var(name) => self.lookup(name).to_string(),
            ExprKind::Unary { op, operand } => match (op, &operand.kind) {
                (UnaryOp::Neg, ExprKind::Int(value)) => c_int_literal(-value, ty),
                (UnaryOp::Neg, _) => {
                    let line = self.source_line(expr.span.start);
                    let operand = self.expr(operand);
                    format!("ccore_neg_{ty}({operand}, {line})")
                }
                (UnaryOp::Not, _) => format!("!{}", self.expr(operand)),
            },
            ExprKind::Binary { op, lhs, rhs } => {
                let operand_ty = lhs.ty.unwrap();
                let lhs = self.expr(lhs);
                let rhs = self.expr(rhs);
                if op.is_arithmetic() {
                    let name = match op {
                        BinaryOp::Add => "add",
                        BinaryOp::Sub => "sub",
                        BinaryOp::Mul => "mul",
                        BinaryOp::Div => "div",
                        BinaryOp::Rem => "rem",
                        _ => unreachable!(),
                    };
                    let line = self.source_line(expr.span.start);
                    format!("ccore_{name}_{operand_ty}({lhs}, {rhs}, {line})")
                } else {
                    format!("({lhs} {} {rhs})", op.symbol())
                }
            }
            ExprKind::Call { callee, args } if callee == BUILTIN_PRINTLN => {
                let arg_ty = args[0].ty.unwrap();
                let arg = self.expr(&args[0]);
                match arg_ty {
                    Type::Str => format!("puts({arg})"),
                    Type::I32 => format!("printf(\"%\" PRId32 \"\\n\", {arg})"),
                    Type::I64 => format!("printf(\"%\" PRId64 \"\\n\", {arg})"),
                    Type::Bool => format!("puts({arg} ? \"true\" : \"false\")"),
                    Type::Void => unreachable!(),
                }
            }
            // TODO: C leaves argument evaluation order unspecified. Hoist calls into
            // temporaries so `f(a(), b())` always runs a() before b().
            ExprKind::Call { callee, args } => {
                let args: Vec<String> = args.iter().map(|a| self.expr(a)).collect();
                format!("{}({})", fn_name(callee), args.join(", "))
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn string_escaping() {
        assert_eq!(c_string("a\"b\\c\n"), r#""a\"b\\c\n""#);
        assert_eq!(c_string("what??="), r#""what\?\?=""#);
        assert_eq!(c_string("ż"), r#""\305\274""#);
    }

    #[test]
    fn shadowed_names_dont_collide_with_user_names() {
        use crate::{checker, lexer::Lexer, parser};
        let src = "fn main() { let x = 1; let x = 2; let x_1 = 3; println(x + x_1); }";
        let mut program = parser::parse(Lexer::new(src).tokenize().unwrap()).unwrap();
        checker::check(&mut program).unwrap();
        let c = generate(&program, src, "t.ccr");
        assert!(c.contains("int32_t v_x = 1;"));
        assert!(c.contains("int32_t v_x_1 = 2;"));
        assert!(c.contains("int32_t v_x_1_1 = 3;"));
        assert!(c.contains("ccore_add_i32(v_x_1, v_x_1_1, 1)"));
    }

    #[test]
    fn int_literals() {
        assert_eq!(c_int_literal(42, Type::I32), "42");
        assert_eq!(c_int_literal(i32::MIN as i64, Type::I32), "INT32_MIN");
        assert_eq!(c_int_literal(-5, Type::I64), "INT64_C(-5)");
    }
}
